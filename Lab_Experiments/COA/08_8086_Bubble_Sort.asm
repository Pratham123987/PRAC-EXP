DATA SEGMENT
 ARRAY DB 45H, 12H, 78H, 34H
 COUNT DW 04H
DATA ENDS
CODE SEGMENT
 ASSUME CS:CODE, DS:DATA
START:
 MOV AX, DATA
 MOV DS, AX
 MOV CX, COUNT
 DEC CX
OUTER_LOOP:
 MOV DX, CX
 MOV SI, OFFSET ARRAY
INNER_LOOP:
 MOV AL, [SI]
 CMP AL, [SI+1]
 JC SKIP_SWAP
 XCHG AL, [SI+1]
 MOV [SI], AL
SKIP_SWAP:
 INC SI
 DEC DX
 JNZ INNER_LOOP
 LOOP OUTER_LOOP
 MOV AH, 4CH
 INT 21H
CODE ENDS
END START
